function parse(raw: string): Record<string, LatLon> {
  const out: Record<string, LatLon> = {};
  for (const line of raw.split("\n")) {
    const [code, lat, lon] = line.trim().split(/\s+/);
    if (!code || !lat || !lon) continue;
    const la = Number(lat);
    const lo = Number(lon);
    if (!Number.isFinite(la) || !Number.isFinite(lo)) continue;
    out[code] = { lat: la, lon: lo };
  }
  return out;
}

/** Все страны и территории, для которых есть координаты. */
export const COUNTRY: Record<string, LatLon> = parse(RAW);

/** Коды одним списком: по нему же проверяем, знаком ли код стране. */
export const COUNTRY_CODES: string[] = Object.keys(COUNTRY);

/** Координаты по коду страны; регистр не важен, неизвестный код → null. */
export function countryOf(code: string | undefined | null): LatLon | null {
  if (!code) return null;
  return COUNTRY[code.trim().toLowerCase()] ?? null;
}
