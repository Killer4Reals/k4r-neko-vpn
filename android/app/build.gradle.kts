// Ключ подписи берём из android/keystore.properties (файла нет в репозитории).
// Если файла нет — release собирается неподписанным, и это видно сразу.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

android {
    namespace = "ink.k4r.nekoneko"
    compileSdk = 35

    defaultConfig {
        applicationId = "ink.k4r.nekoneko.vpn"
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "0.1.0"
    }

    signingConfigs {
        if (keystoreProperties.getProperty("storeFile") != null) {
            create("release") {
                storeFile = file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // R8 не включаем: ядро дергается из JNI по именам классов,
            // и сжатие ломает вызовы. Размер и так небольшой.
            isMinifyEnabled = false
            isShrinkResources = false
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
    }
    // libbox.aar — это само ядро sing-box, собранное под Android
    // (scripts/fetch-libbox.ps1 скачивает готовый файл)
    packaging {
        jniLibs {
            useLegacyPackaging = true
        }
    }
}

